test('本地工具保留解释器顺序、选择保存、错误草稿和重启后的配置', async ({dawn}, info) => {
 test.skip(process.platform === 'win32', '此用例的标记程序是 POSIX shell；Windows 命令形状由单元测试验证')
 const custom=join(dawn.dir,'custom uv executable')
 await writeFile(custom,'#!/bin/sh\nprintf "uv-settings-demo-1\\n"\n');await chmod(custom,0o755)
 let page=dawn.page
 await 进设置(page,'内核')
 await expect(page.locator('.ip-setting').first()).toHaveAttribute('aria-label','R 解释器')
 await expect(page.locator('.ip-setting').nth(1)).toHaveAttribute('aria-label','Python 解释器')
 const tools=page.getByRole('region',{name:'本地工具',exact:true})
 await expect(tools.getByRole('group')).toHaveCount(7)
 let uv=tools.getByRole('group',{name:'uv',exact:true})
 await dawn.app.evaluate((_electron, path)=>{process.env.DAWN_PICK_FILES=path},custom)
 await uv.getByRole('button',{name:'选择文件',exact:true}).click()
 await expect(uv.getByRole('textbox')).toHaveValue(custom)
 await expect(uv.getByRole('button',{name:'保存',exact:true})).toBeEnabled()
 await uv.getByRole('button',{name:'保存',exact:true}).click()
 await expect(uv).toContainText('已配置')
 await expect.poll(()=>page.evaluate(async()=> (await window.dawn!.invoke('getLocalTools',{})).data)).toMatchObject({paths:{uv:custom}})
 await expect(tools.getByRole('button',{name:'重新检测工具',exact:true})).toBeEnabled()
 await tools.getByRole('button',{name:'重新检测工具',exact:true}).click()
 await expect(uv).toContainText('uv-settings-demo-1')
 await expect(uv.getByRole('combobox')).toHaveValue(custom)
 await uv.getByRole('textbox').fill(join(dawn.dir,'not-installed'))
 await uv.getByRole('button',{name:'保存',exact:true}).click()
 await expect(uv.getByRole('alert')).toBeVisible()
 await expect(uv.getByRole('textbox')).toHaveValue(join(dawn.dir,'not-installed'))
 await expect.poll(()=>page.evaluate(async()=> (await window.dawn!.invoke('getLocalTools',{})).data)).toMatchObject({paths:{uv:custom}})
 await uv.getByRole('combobox').selectOption(custom)
 await expect(uv.getByRole('button',{name:'保存',exact:true})).toBeDisabled()
 await page.screenshot({path:info.outputPath('local-tools-wide.png')})
 await page.getByRole('button',{name:'收回',exact:true}).click()
 const sash=page.getByRole('separator',{name:'调整面板宽度',exact:true})
 await sash.focus()
 const min=Number(await sash.getAttribute('aria-valuemin'))
 for(let width=Number(await sash.getAttribute('aria-valuenow'));width>min;width-=16) await sash.press('ArrowRight')
 await page.locator('.body').evaluate(async el=>{await Promise.all(el.getAnimations().map(a=>a.finished));await new Promise<void>(r=>requestAnimationFrame(()=>requestAnimationFrame(()=>r())))})
 for(const id of ['uv','pixi','Conda','Mamba','Node.js','npm','Git']) {
  const row=tools.getByRole('group',{name:id,exact:true})
  expect(await row.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
  await row.getByRole('textbox').scrollIntoViewIfNeeded()
  await expect(row.getByRole('textbox')).toBeVisible()
  await expect(row.getByRole('button',{name:'保存',exact:true})).toBeVisible()
 }
 await page.screenshot({path:info.outputPath('local-tools-narrow.png')})
 page=await dawn.重开()
 await 进设置(page,'内核')
 uv=page.getByRole('region',{name:'本地工具',exact:true}).getByRole('group',{name:'uv',exact:true})
 await expect(uv.getByRole('textbox')).toHaveValue(custom)
 await uv.getByRole('textbox').fill('')
 await uv.getByRole('button',{name:'保存',exact:true}).click()
 await expect.poll(()=>page.evaluate(async()=> (await window.dawn!.invoke('getLocalTools',{})).data)).toMatchObject({paths:{}})
 await expect(uv.getByRole('button',{name:'保存',exact:true})).toBeDisabled()
})

