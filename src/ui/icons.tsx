/**
 * 图标（2026-08-12）。
 *
 * 作者：*「我觉得我们的图标也没有 workbuddy 好看，这个我觉得也要学习，
 * 我觉得他们的图标质感非常的棒。」*
 *
 * ## 量出来的三条，质感就出在这里
 *
 * CDP 连上运行中的 WorkBuddy 读它的 60 个 `<svg>`，主力形态是：
 *
 * ```
 * <svg viewBox="0 0 16 16" fill="currentColor" width=16 height=16 aria-hidden="true">
 * 色：rgba(0,0,0,.7)      高亮那颗：rgba(0,0,0,.9)
 * ```
 *
 * 1. **实心，`fill: currentColor`，`stroke: none`。**
 *    我原本猜它是线性描边——**量出来正好相反**。实心的好处不是「好看」，
 *    是它跟着文字色走：那四档透明度（1 / .7 / .5 / .3）一套下来，
 *    图标与它旁边的字**永远在同一档上**，暗色也不用另配一份。
 *    描边图标做不到这件事：`stroke-width` 是绝对的，颜色一淡它就先散掉。
 * 2. **16×16 的画布上画 16px 的图标**，不是把 24 的缩下来——
 *    边缘正好压在像素上，不发虚。
 * 3. **`aria-hidden="true"`**：图标从不承担含义，含义在它旁边的字里。
 *
 * ## 我们不取它的 path
 *
 * 与读 Hermes / Rho 同一条纪律：**读事实，不读表达**。
 * 量到的是「16px / 实心 / currentColor」这三条**做法**，
 * 那些 `d="M6.6651 0.0001L8.747…"` 是它的表达，一个字节都不抄。
 * 下面每一个 path 都是照着这三条自己画的。
 *
 * ## 为什么不是 emoji
 *
 * 此前侧栏用的是 `💬` `📁` `＋`。emoji 是**彩色字形**——
 * 它吃不到 `currentColor`，于是永远脱离那四档层次；
 * 而且它跟着操作系统的字体走，**同一份代码在两台机器上长得不一样**。
 */

