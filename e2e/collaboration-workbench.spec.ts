import {mkdirSync,writeFileSync} from 'node:fs'
import {join,resolve} from 'node:path'
import {test,expect,在项目里开会话,进坞} from './fixtures.js'
const evidence=resolve(process.env.DAWN_COLLABORATION_EVIDENCE_DIR??'docs/validation/collaboration-workbench-20261107/desktop')
test.use({dawnOptions:{gitInit:true,toolCall:[
 {when:'演示协作台锁等待',toolName:'subagent',args:{tasks:[{agent:'数据核查',task:'锁演示持有任务，等待工具完成。'},{agent:'统计复核',task:'锁演示等待任务，用一句话确认完成。'}]},once:true},
 {when:'锁演示持有任务',toolName:'bash',args:{command:'sleep 8'},once:true},
]}})
test('shows real collaboration facts with selected details and preserves them through workflow and recovery',async({dawn})=>{
 let page=dawn.page
 mkdirSync(join(dawn.workspace,'.dawn/agents'),{recursive:true})
 for(const name of ['数据核查','统计复核'])writeFileSync(join(dawn.workspace,'.dawn/agents',name+'.md'),`---\nname: ${name}\ndescription: 协作台演示\ntools: read,bash\n---\n按指定工具执行，只回复实际结果。`)
 mkdirSync(evidence,{recursive:true})
 await 在项目里开会话(page)
 await page.locator('main.main .composer textarea').fill('演示协作台锁等待')
 await page.getByRole('button',{name:'发送',exact:true}).click()
 await 进坞(page,'团队')
 let overview=page.getByRole('region',{name:'运行总览',exact:true})
 await expect(overview.locator('.collaboration-row')).toHaveCount(2)
 await overview.getByRole('button',{name:'统计复核',exact:true}).click()
 await expect(overview.locator('.collaboration-detail .run-activity')).toContainText('等待产物锁')
 await page.screenshot({path:join(evidence,'phase-a-lock-wait.png')})
 await expect(overview.locator('.collaboration-row').filter({hasText:'执行完成'})).toHaveCount(2)
 await overview.getByRole('tab',{name:'产物'}).click()
 await expect(overview.locator('.collaboration-detail')).toContainText('暂无宿主验收回执')
 await expect(overview.locator('.collaboration-detail')).toContainText('产物版本 0')
 await page.screenshot({path:join(evidence,'phase-a-artifacts.png')})
 if(process.env.DAWN_COLLABORATION_PHASE==='a')return
 await expect(page.getByRole('button',{name:'打开协作：2 项任务 · 0 项验收通过',exact:true})).toBeVisible()
 await overview.getByRole('button',{name:'展开流程工作台',exact:true}).click()
 await expect(overview.getByRole('region',{name:'流程工作台'})).toBeVisible()
 await expect(overview.locator('[data-workflow-edge]')).toHaveCount(0)
 await overview.getByRole('button',{name:'统计复核',exact:true}).click()
 await expect(overview.getByRole('tab',{name:'产物'})).toHaveAttribute('aria-selected','true')
 await overview.getByRole('button',{name:'收起检查面板'}).click()
 await page.screenshot({path:join(evidence,'phase-b-workflow.png')})
 await overview.getByRole('button',{name:'返回对话协作台',exact:true}).click()
 await overview.getByRole('button',{name:'数据核查',exact:true}).click()
 await expect(overview.locator('.collaboration-detail')).toHaveAttribute('data-selected-run',await overview.locator('.collaboration-row').first().getAttribute('data-run')??'')
 await page.screenshot({path:join(evidence,'phase-b-conversation.png')})
 // A second owner must never inherit A's roster, selection, or expanded modal.
 await overview.getByRole('tab',{name:'记录',exact:true}).click()
 await page.getByRole('button',{name:'新建任务',exact:true}).click()
 await page.locator('main.main .composer textarea').fill('会话隔离核查：只回复确认，不创建子任务。')
 await page.getByRole('button',{name:'发送',exact:true}).click()
 await expect(page.locator('main.main').getByRole('button',{name:'停止',exact:true})).toHaveCount(0)
 await 进坞(page,'团队')
 overview=page.getByRole('region',{name:'运行总览',exact:true})
 await expect(overview.locator('.collaboration-row')).toHaveCount(0)
 await expect(overview).toContainText('这段会话没有团队')
 await expect(page.getByRole('button',{name:'打开协作：2 项任务 · 0 项验收通过',exact:true})).toHaveCount(0)
 await page.screenshot({path:join(evidence,'session-b-isolated.png')})
 await page.getByRole('button',{name:/^演示协作台锁等待/}).click()
 await page.getByRole('button',{name:'打开协作：2 项任务 · 0 项验收通过',exact:true}).click()
 overview=page.getByRole('region',{name:'运行总览',exact:true})
 await expect(overview.locator('.collaboration-row')).toHaveCount(2)
 await expect(overview.getByRole('tab',{name:'记录',exact:true})).toHaveAttribute('aria-selected','true')
 await expect(page.getByRole('dialog',{name:'流程工作台',exact:true})).not.toBeVisible()
 await page.screenshot({path:join(evidence,'session-a-restored.png')})
 page=await dawn.重开()
 await page.getByRole('button',{name:/^演示协作台锁等待/}).click()
 await page.getByRole('button',{name:'打开协作：2 项任务 · 0 项验收通过',exact:true}).click()
 overview=page.getByRole('region',{name:'运行总览',exact:true})
 await expect(overview.locator('.collaboration-row')).toHaveCount(2)
 await expect(overview).toContainText('0 项活跃')
 await expect(overview.locator('.collaboration-row').filter({hasText:'执行完成'})).toHaveCount(2)
 await page.screenshot({path:join(evidence,'phase-c-recovery.png')})
})
