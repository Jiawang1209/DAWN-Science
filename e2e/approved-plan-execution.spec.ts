const out=resolve(process.env.DAWN_APPROVED_PLAN_EVIDENCE_DIR??'docs/validation/plan-execution-workbench-20261108/desktop')
const requestBody=(r:unknown)=>(r as {body?:{messages?:unknown[];max_tokens?:number}}).body
