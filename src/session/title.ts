/**
 * 从第一句用户发言推一个会话标题（2026-08-10）。
 *
 * ## 它回答的问题
 *
 * 作者当天的话：*「我的会话，会话的 ID 怎么都是一个呢？我很难辨别具体是哪个会话了。
 * 这里面应该都向 Hermes、claude code app、codex app 去学习。」*
 *
 * 侧栏此前只画 `agentId`——**同一个 agent 建出来的会话在视觉上完全无法区分**。
 * 那三个应用的做法是同一个：**拿第一句话当名字**。它不完美，但它有一个
 * 别的方案都没有的性质：**不用问用户，而且几乎总是对的**——
 * 人记得住自己开这个会话是要干什么。
 *
 * ## 三条纪律
 *
 * 1. **推不出来就不给标题**（返回 `undefined`），不给一个空串。
 *    空串会在界面上显示成一行空白，看起来像加载失败。
 * 2. **截断了要留记号**。一个被砍过的标题和一个天生就短的标题
 *    看起来一模一样——那正是最坏的地方（与变量预览同一条纪律）。
 * 3. **只取第一行。** 贴一大段数据进来时，第二行往往是表头；
 *    把整段压成一行得到的是一条噪声，而不是一个名字。
 */

/** 标题的字符上界。**一眼能扫完，且放得下侧栏一行** */
export const TITLE_MAX = 30

/**
 * 从一段用户发言推标题。
 *
 * @returns 推不出来时 `undefined`——**不返回空串**
 */
export function deriveSessionTitle(text: string): string | undefined {
  // 只取第一段有内容的行。空行、纯空白行跳过
  const line = text
    .split("\n")
    .map((l) => l.trim())
    .find((l) => l.length > 0)
  if (!line) return undefined

  /**
   * 行内的连续空白压成一个空格。
   *
   * **这一步只作用在一行之内**，与「不许把换行压掉」不冲突：
   * 换行是结构（第二行往往是另一件事），行内的多个空格只是排版。
   */
  const flat = line.replace(/\s+/g, " ")
  if (flat.length <= TITLE_MAX) return flat
  // **截断留记号**：省略号本身就是「这里还有」的意思
  return `${flat.slice(0, TITLE_MAX)}…`
}
