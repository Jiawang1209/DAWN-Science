import {mkdirSync,writeFileSync} from 'node:fs'
import {join,resolve} from 'node:path'
import {test,expect,在项目里开会话,进坞} from './fixtures.js'
const evidence=resolve(process.env.DAWN_MODE_MEMBER_EVIDENCE_DIR??'docs/validation/mode-member-workspace-20261108/desktop')
test.use({dawnOptions:{gitInit:true}})
test('automatic arrangement is the default and does not ask for a task count',async({dawn})=>{
 const{page}=dawn;await 在项目里开会话(page);await 进坞(page,'团队')
 const auto=page.getByRole('region',{name:'自动安排',exact:true})
 await expect(auto).toBeVisible();await expect(auto.locator('input[type="number"]')).toHaveCount(0)
 await page.locator('main.main .composer textarea').fill('我已有的任务目标')
 await expect(auto.getByRole('textbox',{name:'任务目标',exact:true})).toHaveValue('我已有的任务目标')
 await expect(auto.getByRole('button',{name:'生成安排',exact:true})).toBeEnabled()
})
test('member process and continuation return to the exact expanded collaboration selection',async({dawn})=>{
 const{page,workspace}=dawn;mkdirSync(evidence,{recursive:true});writeFileSync(join(workspace,'README.md'),'# local member fixture\n')
 await 在项目里开会话(page)
 await page.locator('main.main .composer textarea').fill('派子agent看看这个仓库')
 await page.locator('main.main').getByRole('button',{name:'发送',exact:true}).click()
 await expect(page.locator('main.main .chip-group .chip').first()).toHaveAttribute('data-status','ok')
 await expect(page.locator('main.main').getByRole('button',{name:'停止',exact:true})).toHaveCount(0)
 await 进坞(page,'团队')
 let overview=page.getByRole('region',{name:'运行总览',exact:true})
 await overview.getByRole('tab',{name:'记录',exact:true}).click()
 await overview.getByRole('button',{name:'展开流程工作台',exact:true}).click()
 await overview.locator('[data-member-card]').first().click()
 const selected=await overview.locator('.collaboration-detail').getAttribute('data-selected-run')
 await page.screenshot({path:join(evidence,'stage-b-member.png')})
 await overview.getByRole('button',{name:'查看子任务过程',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'流程工作台',exact:true})).toHaveCount(0)
 const pane=page.locator('.subagent-pane')
 await expect(pane.locator('.subagent-turns')).toContainText('我先读一下 README。')
 await expect(pane.getByRole('button',{name:'返回协作台',exact:true})).toBeVisible()
 await pane.getByRole('textbox',{name:'接着问它',exact:true}).fill('再说一句')
 await pane.getByRole('button',{name:'接着问',exact:true}).click()
 await expect(pane.locator('.subagent-message.user').filter({hasText:'再说一句'})).toHaveCount(1)
 await expect(pane).not.toHaveAttribute('data-asking','1')
 await page.screenshot({path:join(evidence,'stage-b-conversation.png')})
 await pane.getByRole('button',{name:'返回协作台',exact:true}).click()
 overview=page.getByRole('region',{name:'运行总览',exact:true})
 await expect(page.getByRole('dialog',{name:'流程工作台',exact:true})).toBeVisible()
 await expect(overview.getByRole('tab',{name:'记录',exact:true})).toHaveAttribute('aria-selected','true')
 await expect(overview.locator('.collaboration-detail')).toHaveAttribute('data-selected-run',selected!)
 await expect(overview.getByRole('button',{name:'收起检查面板',exact:true})).toBeFocused()
 await page.screenshot({path:join(evidence,'stage-b-return.png')})
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'新建任务',exact:true}).click()
 await expect(page.locator('.subagent-pane')).toHaveCount(0)
 const reopened=await dawn.重开()
 await reopened.getByRole('button',{name:/^派子agent看看这个仓库/}).click()
 await 进坞(reopened,'团队')
 const restored=reopened.getByRole('region',{name:'运行总览',exact:true})
 await expect(restored.locator('.collaboration-row')).toHaveCount(1)
 await expect(restored).toContainText('0 项活跃')
 await expect(reopened.getByRole('dialog',{name:'流程工作台',exact:true})).toHaveCount(0)
 await expect(reopened.getByRole('button',{name:'返回协作台',exact:true})).toHaveCount(0)
 await reopened.screenshot({path:join(evidence,'stage-c-recovery.png')})
})
