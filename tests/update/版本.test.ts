/**
 * 版本比较。**这是整条更新链上最容易被字符串比较毁掉的一环**：
 * `"0.0.10" > "0.0.9"` 在字符串里是 false，于是 0.0.10 发出去之后，
 * 装着 0.0.9 的人永远看不到它，而且**没有任何报错**——这正是最坏的一种坏。
 */
import { describe, expect, it } from "vitest"
import { 解析版本, 比版本, 是更新的 } from "../../src/update/版本.js"

describe("解析版本", () => {
  it("认 tag 上的 v 前缀", () => {
    expect(解析版本("v0.0.3")).toEqual(解析版本("0.0.3"))
  })
  it("垃圾串抛错，不当成 0", () => {
    // 静默当成 0.0.0 的后果：GitHub 回一个畸形 tag，我们判定「有新版」并让人去下一个不存在的东西
    for (const 坏 of ["", "latest", "v", "0.0", "0.0.x", "１.０.０"]) {
      expect(() => 解析版本(坏), 坏).toThrow()
    }
  })
})

describe("比版本", () => {
  it("按数值比，不按字符串比", () => {
    expect(比版本("0.0.10", "0.0.9")).toBe(1)
    expect(比版本("0.10.0", "0.9.0")).toBe(1)
    expect(比版本("1.0.0", "0.99.99")).toBe(1)
  })
  it("相等就是 0", () => {
    expect(比版本("v0.0.2", "0.0.2")).toBe(0)
  })
  it("预发布排在同号正式版之前", () => {
    expect(比版本("0.1.0-rc1", "0.1.0")).toBe(-1)
    expect(比版本("0.1.0-rc1", "0.1.0-rc2")).toBe(-1)
    expect(比版本("0.1.0-rc2", "0.0.9")).toBe(1)
  })
})

describe("是更新的", () => {
  it("只有严格更新才算", () => {
    expect(是更新的("0.0.3", "0.0.2")).toBe(true)
    expect(是更新的("0.0.2", "0.0.2")).toBe(false)
    // 装了开发版比线上还新时**不提示**（否则每次本地打包都会被劝降级）
    expect(是更新的("0.0.2", "0.0.3")).toBe(false)
  })
})
