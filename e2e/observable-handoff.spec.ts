import {mkdirSync,writeFileSync,readdirSync,readFileSync} from 'node:fs'
import {join,resolve} from 'node:path'
import {test,expect,在项目里开会话,进坞} from './fixtures.js'
const evidence=resolve(process.env.DAWN_HANDOFF_EVIDENCE_DIR??'docs/validation/observable-handoff-20261106')
test.describe('observable delegation',()=>{
 test.use({dawnOptions:{gitInit:true,toolCall:{toolName:'subagent',args:{agent:'scout',task:'请确认已收到交接背景，用一句话回答。',handoff:{recentMessages:1}},once:true}}})
 test('shows real orchestration and immutable parent handoff; opens the actual child transcript',async({dawn})=>{
  const {page,workspace}=dawn
  mkdirSync(join(workspace,'.dawn/agents'),{recursive:true})
  writeFileSync(join(workspace,'.dawn/agents/scout.md'),'---\nname: scout\ndescription: 只读踏勘\ntools: read,ls\n---\n只读查看；用一句话回答。\n')
  await 在项目里开会话(page)
  await page.getByPlaceholder(/输入问题/).fill('保留原始样本，单位为 m；仅汇总均值，不修改原文件。')
  await page.getByRole('button',{name:'发送',exact:true}).click()
  await expect(page.locator('.tool').filter({hasText:'subagent'}).first()).toHaveAttribute('data-status','ok',{timeout:60000})
  await 进坞(page,'团队')
  const overview=page.getByRole('region',{name:'运行总览',exact:true})
  await overview.getByRole('tab',{name:'交接',exact:true}).click()
  await expect(overview).toContainText('执行完成')
  await expect(overview).toContainText('执行代次 1')
  mkdirSync(evidence,{recursive:true})
  await page.screenshot({path:join(evidence,'phase-a-overview.png')})
  await overview.locator('summary').filter({hasText:'已冻结交接'}).click()
  await expect(overview.locator('pre')).toContainText('保留原始样本，单位为 m')
  expect(await overview.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
  await page.screenshot({path:join(evidence,'phase-b-handoff.png')})
  const sessions=join(workspace,'.dawn/sessions'),sid=readdirSync(sessions)[0]!,root=join(sessions,sid,'subagents'),call=readdirSync(root)[0]!,dir=join(root,call,'0')
  const originalHandoff=readFileSync(join(dir,'handoff.json'),'utf8'),capsule=JSON.parse(originalHandoff)
  expect(capsule.sourceSessionId).toBe(sid)
  expect(capsule.entries).toHaveLength(1)
  const transcript=readFileSync(join(dir,'transcript',readdirSync(join(dir,'transcript'))[0]!),'utf8')
  expect(transcript).toContain(capsule.sha256)
  expect(transcript).toContain('保留原始样本')
  writeFileSync(join(evidence,'actual-handoff.json'),JSON.stringify({capsule,metadata:JSON.parse(readFileSync(join(dir,'meta.json'),'utf8')),verifiedInActualChildTranscript:true},null,2))
  await overview.getByRole('button',{name:'查看子任务过程',exact:true}).click()
  await expect(page.locator('.subagent-pane')).toBeVisible()
  const pane=page.locator('.subagent-pane')
  await pane.getByRole('textbox',{name:'接着问它'}).fill('继续核查；沿用第一次交接，不新增背景。')
  await pane.getByRole('button',{name:'接着问',exact:true}).click()
  await expect(pane.locator('.subagent-message.user').filter({hasText:'继续核查；沿用第一次交接'})).toHaveCount(1)
  await expect(pane).not.toHaveAttribute('data-asking','1')
  expect(readFileSync(join(dir,'handoff.json'),'utf8')).toBe(originalHandoff)
  expect(readdirSync(join(dir,'transcript')).filter(f=>f.endsWith('.jsonl'))).toHaveLength(1)
  const restarted=await dawn.重开()
  await restarted.getByRole('button',{name:/^保留原始样本，单位为 m；仅汇总均值，不/}).click()
  await 进坞(restarted,'团队')
  const restored=restarted.getByRole('region',{name:'运行总览',exact:true})
  await restored.getByRole('tab',{name:'交接',exact:true}).click()
  await expect(restored).toContainText('已冻结交接')
  await restored.locator('summary').filter({hasText:'已冻结交接'}).click()
  await expect(restored.locator('pre')).toContainText('保留原始样本，单位为 m')
  expect(readFileSync(join(dir,'handoff.json'),'utf8')).toBe(originalHandoff)
  await restarted.screenshot({path:join(evidence,'phase-b-recovery.png')})
 })
})
