import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Locator } from '@playwright/test'
import { test, expect, 在项目里开会话, 进坞 } from './fixtures.js'

const original = 'value = 1\n# keep this comment\nprint(value)'
const revised = 'value = 1\n# keep this comment\nprint(value + 1)'
async function source(editor: Locator) {
  return editor.evaluate(el => (el as HTMLElement & { cmTile: { root: { view: { state: { sliceDoc(): string } } } } }).cmTile.root.view.state.sliceDoc())
}

test.describe('continuous script association', () => {
  test.use({ dawnOptions: { reply: '```python\n' + revised + '\n```' } })
  test('links once, reuses latest unsaved draft, reviews twice, detaches without changing disk', async ({ dawn }) => {
    const { page } = dawn
    await 在项目里开会话(page)
    const chat = page.locator('.conversation .composer textarea')
    await chat.fill('连续修改原脚本')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
    const pane = page.getByRole('region', { name: '代码编辑区', exact: true })
    const editor = pane.getByRole('textbox', { name: '脚本代码编辑器', exact: true })
    await editor.fill(original)
    await pane.getByRole('textbox', { name: '脚本保存路径', exact: true }).fill('linked.py')
    await pane.getByRole('button', { name: '保存脚本', exact: true }).click()
    const path = join(dawn.workspace, 'linked.py')
    await expect.poll(() => existsSync(path) && readFileSync(path, 'utf8')).toBe(original)
    const badge = page.getByLabel('会话关联脚本', { exact: true })
    await expect(badge).toContainText('linked.py')
    await pane.getByRole('button', { name: '收起代码编辑区', exact: true }).click()
    await chat.fill('输出时加一，保留注释')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    const review = page.getByRole('button', { name: '查看差异', exact: true })
    await expect(review).toHaveCount(1)
    await expect(page.locator('.linked-script-snapshot')).toHaveCount(1)
    expect(await page.locator('.linked-script-snapshot').evaluate(el => (el as HTMLDetailsElement).open)).toBe(false)
    await review.click()
    const dialog = page.getByRole('dialog', { name: '审阅脚本修改', exact: true })
    await expect(dialog).toContainText('基于发送时的完整草稿')
    await expect(dialog.getByRole('radio')).toHaveCount(0)
    await dialog.getByRole('button', { name: '应用到原脚本', exact: true }).click()
    await expect.poll(() => source(editor)).toBe(revised)
    expect(readFileSync(path, 'utf8')).toBe(original)

    // Manual unsaved changes made after apply must be authoritative in the next plain chat turn.
    const manual = original.replace('value = 1', 'value = 2')
    await editor.fill(manual)
    await chat.fill('把 value 恢复为 1，并在输出时加一')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await expect(review).toHaveCount(1)
    const userTurns = page.locator('.turn.user')
    await expect(userTurns.last().locator('.text')).toContainText('把 value 恢复为 1')
    await expect(userTurns.last().locator('.linked-script-snapshot pre')).toContainText(manual)
    await review.click()
    await expect(dialog.locator('[data-kind="del"]')).toContainText(['value = 2', 'print(value)'])
    await dialog.getByRole('button', { name: '应用到原脚本', exact: true }).click()
    await expect.poll(() => source(editor)).toBe(revised)
    await expect(badge).toBeVisible()
    expect(readFileSync(path, 'utf8')).toBe(original)
    await page.screenshot({ path: 'output/playwright/code-editor/linked-script-chat.png' })

    // A reply cannot overwrite edits made after its snapshot was sent.
    await chat.fill('继续优化脚本')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await expect(review).toHaveCount(1)
    await editor.fill(manual)
    await review.click()
    await expect(dialog.getByRole('alert')).toContainText('原脚本草稿已改变')
    await expect(dialog.getByRole('button', { name: '应用到原脚本', exact: true })).toBeDisabled()
    await dialog.getByRole('button', { name: '暂不应用', exact: true }).click()
    await badge.getByRole('button', { name: '结束脚本联动', exact: true }).click()
    await expect(badge).toHaveCount(0)
    await chat.fill('现在普通聊天')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await expect(page.getByRole('button', { name: '在旁边编辑', exact: true })).toHaveCount(2)
    await expect(userTurns.last().locator('.linked-script-snapshot')).toHaveCount(0)
    expect(readFileSync(path, 'utf8')).toBe(original)
  })
  test('only entering another script editor retargets the conversation and a new chat starts unlinked', async ({ dawn }) => {
    const { page } = dawn
    writeFileSync(join(dawn.workspace, 'second.py'), 'print("second script")')
    await 在项目里开会话(page)
    const chat = page.locator('.conversation .composer textarea')
    await chat.fill('切换脚本关联')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
    const pane = page.getByRole('region', { name: '代码编辑区', exact: true })
    const editor = pane.getByRole('textbox', { name: '脚本代码编辑器', exact: true })
    await editor.fill(original)
    await pane.getByRole('textbox', { name: '脚本保存路径', exact: true }).fill('first.py')
    await pane.getByRole('button', { name: '保存脚本', exact: true }).click()
    const badge = page.getByLabel('会话关联脚本', { exact: true })
    await expect(badge).toContainText('first.py')
    const firstTitle = (await page.getByRole('tab', { selected: true }).innerText()).trim()
    await pane.getByRole('button', { name: '收起代码编辑区', exact: true }).click()
    await 进坞(page, '文件')
    await page.getByRole('button', { name: /^second\.py/ }).click()
    // File preview is read-only browsing, not a change of editing intent.
    await expect(badge).toContainText('first.py')
    await page.getByRole('button', { name: '编辑脚本', exact: true }).click()
    await expect(badge).toContainText('second.py')
    await expect.poll(() => source(editor)).toBe('print("second script")')
    await badge.getByRole('button', { name: '结束脚本联动', exact: true }).click()
    await expect(badge).toHaveCount(0)
    await expect(pane).toHaveCount(0)
    await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
    await expect(badge).toContainText('first.py')
    await expect.poll(() => source(editor)).toBe(original)
    await page.getByRole('button', { name: '在这里再开一段', exact: true }).click()
    await expect(badge).toHaveCount(0)
    await page.getByRole('tab', { name: firstTitle, exact: true }).click()
    await expect(badge).toContainText('first.py')
  })

})
