  await expect(card.getByRole('alert')).toContainText('副作用')
  writeFileSync(join(out,'stop-request-kinds.json'),JSON.stringify(dawn.requests.map(r=>({contractRequest:JSON.stringify(requestBody(r)?.messages??[]).includes('任务契约（范围已冻结）'),maxTokens:requestBody(r)?.max_tokens,messageCount:requestBody(r)?.messages?.length})),null,2))
  expect(taskRequests()).toBe(before)
