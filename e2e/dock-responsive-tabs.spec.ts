import { 全部房客 } from "../src/ui/state/right-dock.js"
import { test, expect, 在项目里开会话, 进坞 } from "./fixtures.js"

test("标签随实际坞宽度展开收回，当前面板始终可见且菜单只含溢出项", async ({ dawn }, testInfo) => {
  const { page, app } = dawn
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setContentSize(1600, 900))
  await 在项目里开会话(page)
  await 进坞(page, "文件")
  // 直接限制实际列宽，保存的宽度 prop 保持不变，专门防止按 prop 猜数量。
  const size = async (width: number) => {
    await page.locator(".body").evaluate((el, width) => { el.style.setProperty("--dawn-dock-w", `${width}px`) }, width)
    await expect.poll(() => page.locator(".right-dock").evaluate(el => el.getBoundingClientRect().width)).toBe(width)
  }
  const tabs = page.locator('.right-dock [role="tab"]:visible')
  await size(280)
  const narrow = await tabs.count()
  await size(480)
  await expect.poll(() => tabs.count()).toBeGreaterThan(narrow)
  await page.mouse.move(0, 0)
  await page.screenshot({ path: testInfo.outputPath("dock-medium.png") })
  await page.locator(".dock-head").screenshot({ path: testInfo.outputPath("dock-medium-header.png") })
  await size(720)
  await expect.poll(() => tabs.count()).toBeGreaterThan(narrow)
  await expect(tabs).toHaveCount(全部房客.length)
  await expect(page.getByRole("button", { name: "更多面板", exact: true })).toHaveCount(0)
  await page.mouse.move(0, 0)
  await page.screenshot({ path: testInfo.outputPath("dock-wide.png") })
  await page.locator(".dock-head").screenshot({ path: testInfo.outputPath("dock-wide-header.png") })
  await 进坞(page, "对话")
  await size(280)
  const selected = page.getByRole("tab", { name: "对话", exact: true })
  await expect(selected).toHaveAttribute("aria-selected", "true")
  await expect(selected).toBeInViewport()
  await expect.poll(() => tabs.count()).toBeLessThan(全部房客.length)
  await page.getByRole("button", { name: "更多面板", exact: true }).click()
  const visible = await tabs.allTextContents()
  const hidden = await page.getByRole("menuitem").allTextContents()
  expect(hidden.length + visible.length).toBe(全部房客.length)
  for (const name of hidden) expect(visible).not.toContain(name)
  await page.getByRole("menu").press("Escape")
  await page.mouse.move(0, 0)
  await page.screenshot({ path: testInfo.outputPath("dock-narrow-current.png") })
  await page.locator(".dock-head").screenshot({ path: testInfo.outputPath("dock-narrow-current-header.png") })
  const bounds = await page.locator(".dock-head").evaluate(el => {
    const buttons = [...el.querySelectorAll<HTMLElement>('[role="tab"], .dock-more > button, .dock-close')].filter(el => getComputedStyle(el).visibility !== "hidden")
    return buttons.map(el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right, center: r.top + r.height / 2 } })
  })
  for (let i = 1; i < bounds.length; i++) {
    expect(bounds[i]!.left).toBeGreaterThanOrEqual(bounds[i - 1]!.right)
    expect(Math.abs(bounds[i]!.center - bounds[0]!.center)).toBeLessThan(1)
  }
  // 模拟计数增长的真实 DOM 尺寸变化，宽度 prop 与容器均不变。
  await page.locator('[data-dock-tab="artifacts"]').evaluate(el => {
    const badge = document.createElement("span"); badge.className = "dock-tab-badge"; badge.textContent = "9999"; el.append(badge)
  })
  await expect(page.getByRole("tab", { name: "产物", exact: true })).toHaveCount(0)
  await page.locator('[data-dock-tab="artifacts"] .dock-tab-badge').evaluate(el => el.remove())
  await expect(page.getByRole("tab", { name: "产物", exact: true })).toBeVisible()
  // 菜单打开时部分展开，会移走原来聚焦的菜单项；键盘仍应停留在剩余菜单中。
  await page.getByRole("button", { name: "更多面板", exact: true }).click()
  await expect(page.getByRole("menuitem").first()).toBeFocused()
  const input = page.locator("main.main").getByPlaceholder(/今天帮你做些什么/)
  await input.focus()
  await size(480)
  await expect(input).toBeFocused({ timeout: 1500 })
  await size(280)
  await page.getByRole("menuitem").first().focus()
  await size(480)
  await expect(page.getByRole("menu")).toBeVisible()
  await expect(page.getByRole("menuitem").first()).toBeFocused({ timeout: 1500 })
  await page.getByRole("menu").press("ArrowDown")
  await expect(page.getByRole("menuitem").nth(1)).toBeFocused()
  await size(720)
  await expect(page.getByRole("menu")).toHaveCount(0)
  await expect(selected).toBeFocused()
})


test("真实拖拽与英文深色下标签自适应，展开时菜单收起并保留当前面板", async ({ dawn }, testInfo) => {
  const { page, app } = dawn
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setContentSize(1600, 900))
  await 在项目里开会话(page)
  await 进坞(page, "对话")
  const sash = page.getByRole("separator", { name: "调整面板宽度", exact: true })
  const resize = async (px: number) => {
    const previous = Number(await sash.getAttribute("aria-valuenow"))
    await expect.poll(() => page.locator(".right-dock").evaluate(el => el.getBoundingClientRect().width)).toBe(previous)
    const box = (await sash.boundingBox())!
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width / 2 - px, box.y + box.height / 2, { steps: 10 })
    await page.mouse.up()
    const expected = Math.min(720, Math.max(280, previous + px))
    await expect(sash).toHaveAttribute("aria-valuenow", String(expected))
    await expect.poll(() => page.locator(".right-dock").evaluate(el => el.getBoundingClientRect().width)).toBe(expected)
  }
  await resize(240)
  await expect(page.locator('.right-dock [role="tab"]:visible')).toHaveCount(全部房客.length)
  await resize(-440)
  await expect.poll(() => page.locator('.right-dock [role="tab"]:visible').count()).toBeLessThan(全部房客.length)
  await expect(page.getByRole("tab", { name: "对话", exact: true })).toBeInViewport()
  await page.getByRole("button", { name: "更多面板", exact: true }).click()
  await expect(page.getByRole("menuitem").first()).toBeFocused()
  await resize(440)
  await expect(page.getByRole("menu")).toHaveCount(0)
  await expect(page.getByRole("tab", { name: "对话", exact: true })).toHaveAttribute("aria-selected", "true")
  await page.addInitScript(() => {
    localStorage.setItem("dawn.global.lang", "en")
    localStorage.setItem("dawn.global.theme", "dark")
  })
  await page.reload()
  await expect(page.getByRole("button", { name: "New task", exact: true })).toBeVisible()
  await page.getByRole("button", { name: /^Panel/ }).click()
  await expect(page.getByRole("tab", { name: "Chat", exact: true })).toHaveAttribute("aria-selected", "true")
  await expect(page.getByRole("tab", { name: "Chat", exact: true })).toBeInViewport()
  await expect.poll(() => page.locator(".right-dock").evaluate(el => el.getBoundingClientRect().width)).toBe(720)
  await expect.poll(() => page.locator('.right-dock [role="tab"]:visible').count()).toBeGreaterThan(3)
  const wide = await page.locator('.right-dock [role="tab"]:visible').count()
  const englishSash = page.getByRole("separator", { name: "Resize panel", exact: true })
  const box = (await englishSash.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 400, box.y + box.height / 2, { steps: 10 })
  await page.mouse.up()
  await expect(englishSash).toHaveAttribute("aria-valuenow", "320")
  await expect.poll(() => page.locator(".right-dock").evaluate(el => el.getBoundingClientRect().width)).toBe(320)
  await expect.poll(() => page.locator('.right-dock [role="tab"]:visible').count()).toBeLessThan(wide)
  await expect(page.getByRole("tab", { name: "Chat", exact: true })).toBeInViewport()
  await page.mouse.move(0, 0)
  await page.screenshot({ path: testInfo.outputPath("dock-english-dark.png") })
  await page.locator(".dock-head").screenshot({ path: testInfo.outputPath("dock-english-dark-header.png") })
})
