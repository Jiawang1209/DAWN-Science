test.describe('stopping bound work',()=>{
 test.use({dawnOptions:{gitInit:true,firstChunkDelayMs:1500}})
 test('stops the approved task, drains its process and never replays it after reopening',async({dawn})=>{
  const{page,workspace}=dawn;writeFileSync(join(workspace,'input.csv'),'x\n1\n2\n3\n')
  await 在项目里开会话(page);await 进坞(page,'团队')
  const auto=page.getByRole('region',{name:'自动安排',exact:true})
  await auto.getByRole('textbox',{name:'任务目标',exact:true}).fill('清洗、建模并独立审阅 input.csv')
  await auto.getByRole('button',{name:'生成安排',exact:true}).click()
  await expect(auto.getByRole('status',{name:'任务块数',exact:true})).toHaveText('3 个任务块')
  await page.locator('main.main .plan-card').getByRole('button',{name:'照这个做',exact:true}).click()
  let overview=page.getByRole('region',{name:'运行总览',exact:true})
  await expect.poll(()=>dawn.requests.filter(r=>JSON.stringify(requestBody(r)?.messages??[]).includes('任务契约（范围已冻结）')).length).toBeGreaterThan(0)
  await overview.getByRole('button',{name:'停止本方案执行',exact:true}).click()
  await expect(overview).toContainText('用户已停止执行')
  await expect(overview.locator('.run-overview-row[data-phase="running"],.run-overview-row[data-phase="stopping"],.run-overview-row[data-phase="queued"]')).toHaveCount(0)
  mkdirSync(out,{recursive:true});await page.screenshot({path:join(out,'stage-b-stopped.png')})
  const reopened=await dawn.重开()
  await reopened.getByRole('button',{name:/^请为以下具体任务自动安排/}).click();await 进坞(reopened,'团队')
  overview=reopened.getByRole('region',{name:'运行总览',exact:true})
  await expect(overview).toContainText('执行已暂停')
  const taskRequests=()=>dawn.requests.filter(r=>JSON.stringify(requestBody(r)?.messages??[]).includes('任务契约（范围已冻结）')).length
  const before=taskRequests(),card=reopened.locator('main.main .plan-card')
  await card.getByRole('button',{name:'开始或继续未执行任务',exact:true}).click()
  await expect(card.getByRole('alert')).toContainText('副作用')
  writeFileSync(join(out,'stop-request-kinds.json'),JSON.stringify(dawn.requests.map(r=>({contractRequest:JSON.stringify(requestBody(r)?.messages??[]).includes('任务契约（范围已冻结）'),maxTokens:requestBody(r)?.max_tokens,messageCount:requestBody(r)?.messages?.length})),null,2))
  expect(taskRequests()).toBe(before)
  await overview.getByRole('button',{name:'结束此安排',exact:true}).click()
  await expect(overview).toContainText('安排已结束，任务记录保留。')
  await reopened.screenshot({path:join(out,'stage-b-retired.png')})
  expect(readFileSync(join(workspace,'input.csv'),'utf8')).toBe('x\n1\n2\n3\n')
 })
})
