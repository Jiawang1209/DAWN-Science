/**
 * 「换一个 LLM」这颗 pill 的菜单里该放谁（2026-08-11）。
 *
 * ## 它存在是因为一次真实的误按
 *
 * 作者：*「同一个对话，我切换模型，依旧会弹出新的对话，而不是继续对话。」*
 *
 * 那颗 pill 的菜单有两组：上面「就地换服务（对话不断）」，
 * 下面「新建会话，用哪个 LLM」。**同一家 DeepSeek 在两组里各出现一次**，
 * 而人是照着「换 LLM」这几个字点的——于是点中了会新开对话的那个。
 *
 * **同样的形状配不同的语义，是最容易让人按错的一种设计**，
 * 而这次的代价不是按错一下：一段对话的上下文就此断在那里。
 *
 * 规则因此改成：**能就地换过去的，就不在「新建会话」那一组里再出现一次**。
 * 想另起一段仍然有路——侧栏那颗「新建会话」。
 */

/**
 * @param agentIds 配置里全部可选的 agent
 * @param kindOf 每个 agent 是怎么接上模型的（`native` 才可能就地换）
 * @param 能就地换 当前这个会话有没有「就地换服务」那一组
 */
export function 新建会话可选的(
  agentIds: readonly string[],
  kindOf: (id: string) => string | undefined,
  能就地换: boolean,
): string[] {
  /**
   * **没有上组时，下组必须是全量。**
   *
   * 一个 CLI 会话（claude / codex）换不了服务，那时下组是唯一的出路；
   * 这时候再过滤，人就一个选项都看不到了——
   * **「看不见的能力等于不存在」的又一种形状**。
   */
  if (!能就地换) return [...agentIds]
  // 一个 API 会话没法半路变成 claude 会话，所以那些仍要留在「新建」这一组
  return agentIds.filter((id) => kindOf(id) !== "native")
}
