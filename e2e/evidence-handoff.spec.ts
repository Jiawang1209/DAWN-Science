import {mkdirSync,writeFileSync,readdirSync,readFileSync} from 'node:fs'
import {join,resolve} from 'node:path'
import {test,expect,在项目里开会话,进坞} from './fixtures.js'
const output=resolve(process.env.DAWN_EVIDENCE_HANDOFF_DIR??'docs/validation/evidence-evaluation-20261107/desktop')
test('selects early context by host ID, shows provenance and preserves it across continuation and restart',async({dawn})=>{
 const {page,workspace}=dawn
 mkdirSync(join(workspace,'.dawn/agents'),{recursive:true});writeFileSync(join(workspace,'.dawn/agents/scout.md'),'---\nname: scout\ndescription: 只读核查\ntools: read,ls\n---\n只读报告收到的要求。')
 await 在项目里开会话(page)
 const composer=page.locator('textarea.composer-field')
 await composer.fill('早期约束：carbon 单位 mg/g；使用算术均值，只丢弃 NA，不能按降雨筛选。保留原始输入。')
 await page.getByRole('button',{name:'发送',exact:true}).click()
 await expect(page.getByRole('button',{name:'停止',exact:true})).toHaveCount(0)
 for(const message of ['建立会话分析路线，先记录输入和步骤。','后续讨论：先解释，不执行。']){
  await composer.fill(message);await page.getByRole('button',{name:'发送',exact:true}).click()
  await expect(page.getByRole('button',{name:'停止',exact:true})).toHaveCount(0)
 }
 await composer.fill('开始执行演示证据交接：把早期约束交给只读 scout。')
 await page.getByRole('button',{name:'发送',exact:true}).click()
 await expect(page.getByRole('button',{name:/scout 完成/})).toBeVisible({timeout:60000})
 await 进坞(page,'团队')
 const overview=page.getByRole('region',{name:'运行总览',exact:true})
  await overview.getByRole('tab',{name:'交接',exact:true}).click()
 await expect(overview).toContainText('已冻结交接')
 await overview.locator('summary').filter({hasText:'已冻结交接'}).click()
 await expect(overview.locator('pre').filter({hasText:'早期约束'})).toContainText('早期约束')
 await expect(overview).toContainText('历史版本尚未重新核验')
 await expect(overview).toContainText('步骤 S1')
 mkdirSync(output,{recursive:true});await page.screenshot({path:join(output,'early-evidence-handoff.png')})
 await overview.locator('.run-handoff').screenshot({path:join(output,'early-evidence-details.png')})
 const sessions=join(workspace,'.dawn/sessions'),sid=readdirSync(sessions)[0]!,runs=join(sessions,sid,'subagents'),call=readdirSync(runs)[0]!,dir=join(runs,call,'0')
 const original=readFileSync(join(dir,'handoff.json'),'utf8'),capsule=JSON.parse(original)
 expect(capsule.version).toBe(2);expect(capsule.entries[0].text).toContain('早期约束');expect(capsule.entries[0].text).not.toContain('演示证据交接')
 await overview.getByRole('button',{name:'查看子任务过程',exact:true}).click()
 const pane=page.locator('.subagent-pane')
 await pane.getByRole('textbox',{name:'接着问它'}).fill('继续，沿用原背景，不增加权限。');await pane.getByRole('button',{name:'接着问',exact:true}).click()
 await expect(pane.locator('.subagent-message.user').filter({hasText:'继续，沿用原背景'})).toHaveCount(1)
 await expect(pane).not.toHaveAttribute('data-asking','1')
 expect(readFileSync(join(dir,'handoff.json'),'utf8')).toBe(original)
 const restarted=await dawn.重开()
 await restarted.getByRole('button',{name:/^早期约束/}).click()
 await 进坞(restarted,'团队')
 const restored=restarted.getByRole('region',{name:'运行总览',exact:true})
  await restored.getByRole('tab',{name:'交接',exact:true}).click()
 await expect(restored).toContainText('已冻结交接');await restored.locator('summary').filter({hasText:'已冻结交接'}).click()
 await expect(restored.locator('pre').filter({hasText:'早期约束'})).toContainText('不能按降雨筛选')
 expect(readFileSync(join(dir,'handoff.json'),'utf8')).toBe(original)
 await restarted.screenshot({path:join(output,'recovered-evidence-handoff.png')})
 await restored.locator('.run-handoff').screenshot({path:join(output,'recovered-evidence-details.png')})
 writeFileSync(join(output,'handoff-proof.json'),JSON.stringify({capsule,continuedUnchanged:true,restartedUnchanged:true,readOnlyScope:JSON.parse(readFileSync(join(dir,'meta.json'),'utf8')).settings.scope},null,2)+'\n')
})
