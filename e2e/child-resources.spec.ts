import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { test, expect, 在项目里开会话 } from "./fixtures.js"
type RecordedRequest = {body: {messages?: {role: string; content: unknown}[]}}

test.use({dawnOptions: {gitInit: true}})
test("真实主会话派单 → 子资源查询可见 → 续问刷新 → 重启恢复", async ({dawn}) => {
  const {page, workspace} = dawn
  const skill = join(workspace, ".dawn/skills/resource-fixture"); mkdirSync(skill, {recursive: true})
  writeFileSync(join(skill, "SKILL.md"), "---\nname: resource-fixture\ndescription: 资源验收技能\n---\nCHILD_SKILL_EVIDENCE：参数集中并记录随机种子")
  const memory = join(workspace, ".dawn/memory"); mkdirSync(memory, {recursive: true})
  writeFileSync(join(memory, "KEY.md"), "[branch:main,master] 固定参数 CHILD_MEMORY_EVIDENCE：种子 42\n")
  await 在项目里开会话(page)
  await page.getByPlaceholder(/今天帮你做些什么/).fill("派子agent查资源")
  await page.getByRole("button", {name: "发送", exact: true}).click()
  const chip = page.locator("main.main .chip-group .chip").first()
  await expect(chip).toHaveAttribute("data-status", "ok", {timeout: 60_000})
  await expect(page.locator("main.main").getByRole("button", {name: "停止", exact: true})).toHaveCount(0)
  await chip.click()
  const pane = page.locator(".subagent-pane")
  await expect(pane.locator('.tool[data-tool-name^="resource_"]')).toHaveCount(4)
  await expect(pane.locator(".subagent-title")).toHaveText("数据质量审计员")
  await expect(pane.locator(".who-avatar")).toHaveCount(0)
  await expect(pane.locator(".tool-head").filter({hasText: "查询相关技能"})).toHaveCount(1)
  expect(await pane.locator(".tool-head").allTextContents()).not.toEqual(expect.arrayContaining([expect.stringContaining('"id":')]))
  const polishDir = join(process.cwd(), "tmp/subagent-polish"); mkdirSync(polishDir, {recursive: true})
  await pane.screenshot({path: join(polishDir, "panel-initial.png")})
  const requests = (dawn.requests as RecordedRequest[]).filter(r => r.body.messages?.some(m => m.role === "user" && JSON.stringify(m.content).includes("子资源验收：")))
  expect(requests.length).toBeGreaterThanOrEqual(5)
  expect(JSON.stringify(requests[0]!.body.messages)).not.toContain("CHILD_SKILL_EVIDENCE")
  expect(JSON.stringify(requests[0]!.body.messages)).not.toContain("CHILD_MEMORY_EVIDENCE")
  expect(JSON.stringify(requests.at(-1)!.body.messages)).toContain("CHILD_SKILL_EVIDENCE")
  expect(JSON.stringify(requests.at(-1)!.body.messages)).toContain("CHILD_MEMORY_EVIDENCE")
  writeFileSync(join(memory, "KEY.md"), "固定参数 CHILD_REFRESHED_EVIDENCE：种子 17\n")
  await pane.getByRole("textbox", {name: "接着问它"}).fill("子资源验收：续问刷新")
  await pane.getByRole("button", {name: "接着问", exact: true}).click()
  await expect(pane.locator('.tool[data-tool-name^="resource_"]')).toHaveCount(8)
  await expect.poll(() => JSON.stringify((dawn.requests as RecordedRequest[]).at(-1)?.body.messages)).toContain("CHILD_REFRESHED_EVIDENCE")
  const screenshotDir = join(process.cwd(), "tmp/child-resources"); mkdirSync(screenshotDir, {recursive: true})
  await page.screenshot({path: join(screenshotDir, "electron-resource-tools.png")})
  // 真窗口/真坞：窄栏不横溢，展开原参数时续问区仍在可见框里。
  await dawn.app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0]!.setContentSize(1440, 960))
  for (const width of [480, 280]) {
    await page.locator(".body").evaluate((el, w) => (el as HTMLElement).style.setProperty("--dawn-dock-w", `${w}px`), width)
    await expect.poll(() => page.locator(".right-dock").evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(width)
    const geometry = await pane.evaluate(el => {
      const box = el.getBoundingClientRect(), footer = el.querySelector(".subagent-ask")!.getBoundingClientRect()
      return {overflow: el.scrollWidth - el.clientWidth, bottom: footer.bottom - box.bottom,
        contentBottom: el.querySelector(".subagent-turns")!.getBoundingClientRect().bottom - footer.top}
    })
    expect(geometry.overflow).toBeLessThanOrEqual(1)
    expect(geometry.bottom).toBeLessThanOrEqual(1)
    expect(geometry.contentBottom).toBeLessThanOrEqual(1)
    await expect(pane.getByRole("button", {name: "接着问", exact: true})).toBeInViewport()
    await pane.screenshot({path: join(polishDir, `panel-light-${width}.png`)})
  }
  const readTool = pane.locator('.tool[data-tool-name="resource_read"]').last()
  await readTool.locator(".tool-head").click()
  await expect(readTool.locator(".tool-input")).toContainText("memory:")
  await expect(pane.getByRole("textbox", {name: "接着问它"})).toBeInViewport()
  await readTool.locator(".tool-head").click()
  const restored = await dawn.重开()
  await restored.getByRole("button", {name: /^派子agent查资源/}).click()
  await restored.locator("main.main .chip-group .chip").first().click()
  await expect(restored.locator('.subagent-pane .tool[data-tool-name^="resource_"]')).toHaveCount(8)
  await restored.getByRole("button", {name: "设置", exact: true}).click()
  await restored.getByRole("button", {name: "展开", exact: true}).click()
  await restored.getByRole("radio", {name: "暗色", exact: true}).click()
  await expect(restored.locator("html.dawn-dark")).toHaveCount(1)
  await restored.getByRole("button", {name: "返回", exact: true}).click()
  await restored.locator("main.main .chip-group .chip").first().click()
  await restored.locator(".body").evaluate(el => (el as HTMLElement).style.setProperty("--dawn-dock-w", "280px"))
  await expect.poll(() => restored.locator(".right-dock").evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(280)
  await expect(restored.locator(".subagent-pane").getByRole("textbox", {name: "接着问它"})).toBeInViewport()
  await restored.locator(".subagent-pane").screenshot({path: join(polishDir, "panel-dark-280.png")})
})
