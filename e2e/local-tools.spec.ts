test('从工作台重新查看四步引导，保留模型和环境配置', async ({dawn}) => {
 const {page}=dawn
 const read=()=>page.evaluate(async()=>({credentials:(await window.dawn!.invoke('listCredentials',{})).data,interpreters:(await window.dawn!.invoke('getInterpreters',{})).data,tools:(await window.dawn!.invoke('getLocalTools',{})).data}))
 const before=await read()
 await page.locator(".composer textarea").fill("保留这条尚未发送的研究问题")
 const guide=page.locator('.statusbar').getByRole('button',{name:'导航栏',exact:true})
 await expect(guide).toBeVisible({timeout:1000});await guide.click()
 const wizard=page.locator('.setup-wizard')
 await expect(wizard.getByRole('heading',{name:'欢迎使用 DAWN Science',exact:true})).toBeVisible()
 await wizard.getByRole('button',{name:'下一页',exact:true}).click()
 await wizard.getByRole('button',{name:'下一页',exact:true}).click()
 await expect(wizard.getByRole('heading',{name:'连接 AI 模型',exact:true})).toBeVisible()
 await wizard.getByRole('button',{name:'稍后配置',exact:true}).click()
 await expect(wizard.getByRole('table',{name:'本地环境路径',exact:true})).toBeVisible()
 await wizard.getByRole("radio",{name:"English",exact:true}).click()
 await wizard.getByRole("radio",{name:"中文",exact:true}).click()
 await wizard.getByRole('button',{name:'先跳过',exact:true}).click()
 await expect(wizard).toHaveCount(0)
 expect(await read()).toEqual(before)
 await expect(page.locator(".composer textarea")).toHaveValue("保留这条尚未发送的研究问题",{timeout:1500})
 await page.getByRole("button",{name:"发送",exact:true}).click()
 await expect(page.getByText(CANNED_REPLY,{exact:false}).last()).toBeVisible()
 await page.locator(".composer textarea").fill("会话中的下一条草稿")
 await guide.click()
 await expect(wizard.getByRole("heading",{name:"欢迎使用 DAWN Science",exact:true})).toBeVisible()
 await wizard.getByRole("button",{name:"先跳过",exact:true}).click()
 await expect(page.getByText(CANNED_REPLY,{exact:false}).last()).toBeVisible()
 await expect(page.locator(".composer textarea")).toHaveValue("会话中的下一条草稿")
})


