import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { test, expect, 在项目里开会话, 进坞 } from './fixtures.js'

const kernelJson = join(homedir(), 'Library', 'Jupyter', 'kernels', 'dawn-spike', 'kernel.json')
const script = 'value = 40\nprint(value + 2)\n'
const reply = '可以直接修改这个脚本：\n\n```python\n' + script + '```'
const modifier = process.platform === 'darwin' ? 'Meta' : 'Control'

test.use({ dawnOptions: { reply, realKernels: true } })

test('code opens beside the existing conversation; saves, conflict recovery and draft retention use real files', async ({ dawn }) => {
  const { page, workspace } = dawn
  mkdirSync(join(workspace, 'scripts'), { recursive: true })
  writeFileSync(join(workspace, 'scripts', 'existing.py'), 'print("original")\n')
  await 在项目里开会话(page)
  const chat = page.locator('.conversation .composer textarea')
  await chat.fill('生成一个 Python 脚本')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
  const pane = page.getByRole('region', { name: '代码编辑区', exact: true })
  const editor = pane.getByRole('textbox', { name: '脚本代码编辑器', exact: true })
  await expect(chat).toBeVisible()
  await expect(page.locator('.conversation')).toHaveCount(1)
  await expect(editor).toContainText('value = 40')
  await pane.getByRole('textbox', { name: '脚本保存路径', exact: true }).fill('scripts/analysis.py')
  await editor.fill('value = 41\nprint(value + 1)')
  await pane.getByRole('button', { name: '保存脚本', exact: true }).click()
  await expect.poll(() => existsSync(join(workspace, 'scripts/analysis.py')) && readFileSync(join(workspace, 'scripts/analysis.py'), 'utf8')).toBe('value = 41\nprint(value + 1)')
  await editor.fill('value = 42\nprint(value)')
  await editor.press(`${modifier}+s`)
  await expect.poll(() => readFileSync(join(workspace, 'scripts/analysis.py'), 'utf8')).toBe('value = 42\nprint(value)')
  await editor.fill('value = 43\nprint(value)')
  await pane.getByRole('button', { name: '收起代码编辑区', exact: true }).click()
  await expect(pane).toHaveCount(0)
  await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
  await expect(editor).toContainText('value = 43')
  writeFileSync(join(workspace, 'scripts/analysis.py'), 'print("external writer")\n')
  await pane.getByRole('button', { name: '保存脚本', exact: true }).click()
  await expect(pane.getByRole('alert')).toContainText('保存冲突')
  await expect(editor).toContainText('value = 43')
  expect(readFileSync(join(workspace, 'scripts/analysis.py'), 'utf8')).toContain('external writer')
  await pane.getByRole('button', { name: '放弃草稿并重读', exact: true }).click()
  await expect(editor).toContainText('external writer')
  await pane.getByRole('button', { name: '收起代码编辑区', exact: true }).click()
  await 进坞(page, '文件')
  await page.getByRole('button', { name: 'scripts', exact: true }).click()
  await page.getByRole('button', { name: /^existing\.py/ }).click()
  await page.getByRole('button', { name: '编辑脚本', exact: true }).click()
  await expect(editor).toContainText('original')
  await editor.fill('print("saved from file preview")')
  await pane.getByRole('button', { name: '保存脚本', exact: true }).click()
  await expect.poll(() => readFileSync(join(workspace, 'scripts/existing.py'), 'utf8')).toBe('print("saved from file preview")')
  await page.screenshot({ path: 'output/playwright/code-editor/side-editor-light.png' })
  await page.evaluate(() => document.documentElement.classList.add('dawn-dark'))
  await page.screenshot({ path: 'output/playwright/code-editor/side-editor-dark.png' })
  await page.setViewportSize({ width: 1000, height: 740 })
  await expect(pane.getByRole('button', { name: '保存脚本', exact: true })).toBeVisible()
  await expect(chat).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'output/playwright/code-editor/side-editor-narrow.png' })
})

test('selected code runs in the current real Python kernel and output matches the selected snippet', async ({ dawn }) => {
  test.skip(!existsSync(kernelJson), '本机未配置 dawn-spike Python 内核')
  const { page } = dawn
  const python = (JSON.parse(readFileSync(kernelJson, 'utf8')) as { argv: string[] }).argv[0]!
  const configured = await page.evaluate(path => window.dawn!.invoke('setInterpreter', { language: 'python', path }), python)
  expect(configured.ok).toBe(true)
  await 在项目里开会话(page)
  await page.getByPlaceholder(/输入问题/).fill('生成一个 Python 脚本')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
  const pane = page.getByRole('region', { name: '代码编辑区', exact: true })
  const editor = pane.getByRole('textbox', { name: '脚本代码编辑器', exact: true })
  await editor.fill('shared_value = 41\nprint(shared_value + 1)')
  await editor.press(`${modifier}+Enter`)
  await expect(pane.locator('.kout-text')).toContainText('42', { timeout: 45000 })
  await editor.fill('raise RuntimeError("whole script must not run")\nprint(shared_value + 2)')
  await editor.focus()
  await editor.press(`${modifier}+a`)
  await editor.press('ArrowRight')
  await editor.press('Shift+Home')
  await expect(pane.getByRole('button', { name: '运行选区', exact: true })).toBeVisible()
  await pane.getByRole('button', { name: '运行选区', exact: true }).click()
  await expect(pane.locator('.kout-text')).toContainText('43', { timeout: 45000 })
  await expect(pane.locator('.kout-text')).not.toContainText('whole script must not run')
  await pane.getByRole('button', { name: '带入对话', exact: true }).click()
  await expect(page.locator('.conversation .composer textarea')).toHaveValue(/print\(shared_value \+ 2\)/)
  await page.screenshot({ path: 'output/playwright/code-editor/selection-execution.png' })
})

test('switching conversations hides an unrelated editor and preserves the original draft', async ({ dawn }) => {
  const { page } = dawn
  await 在项目里开会话(page)
  await page.locator('.conversation .composer textarea').fill('生成一个 Python 脚本')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
  const pane = page.getByRole('region', { name: '代码编辑区', exact: true })
  await pane.getByRole('textbox', { name: '脚本代码编辑器', exact: true }).fill('print("retained session A draft")')
  await page.getByRole('button', { name: '在这里再开一段', exact: true }).click()
  await expect(pane).toHaveCount(0)
  await page.getByRole('tab', { name: '生成一个 Python 脚本', exact: true }).click()
  await page.getByRole('button', { name: '在旁边编辑', exact: true }).click()
  await expect(pane.getByRole('textbox', { name: '脚本代码编辑器', exact: true })).toContainText('retained session A draft')
})
