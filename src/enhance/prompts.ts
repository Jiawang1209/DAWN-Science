/** 用户消息的包法。**原文放在三引号里**，清洗时据此识别回显 */
export const 包原文 = (text: string) => `请改写下面这段提示词：\n\n"""\n${text}\n"""`

export type 档 = "basic" | "standard" | "expert"

/** 拼 system：纪律 + 方法 +（带参考时）参考规则 */
export function 拼system(带参考: boolean): string {
  return [纪律, 方法, ...(带参考 ? [参考规则] : [])].join("\n\n")
}

/** 拼 user：参考块在前、原文在后 */
export function 拼user(text: string, 参考块: readonly string[]): string {
  return [...参考块, 包原文(text)].join("\n\n")
}
