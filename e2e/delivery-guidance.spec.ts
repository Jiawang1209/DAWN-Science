import {mkdirSync,writeFileSync,readFileSync,existsSync} from 'node:fs'
import {resolve,join} from 'node:path'
import {test,expect,在项目里开会话,进坞} from './fixtures.js'
const out=resolve(process.env.DAWN_DELIVERY_GUIDANCE_EVIDENCE_DIR??'docs/validation/delivery-guidance-20261109/desktop')
test.use({dawnOptions:{gitInit:true}})
test('clarification survives restart, creates a new proposal and executes only after approval',async({dawn})=>{
 let{page}=dawn;const{workspace}=dawn;mkdirSync(out,{recursive:true});writeFileSync(join(workspace,'input.csv'),'x\n1\n2\n3\n')
 await 在项目里开会话(page);await 进坞(page,'团队')
 let auto=page.getByRole('region',{name:'自动安排',exact:true})
 await auto.getByRole('textbox',{name:'任务目标',exact:true}).fill('计算 input.csv 均值，单位未提供')
 await auto.getByRole('button',{name:'生成安排',exact:true}).click()
 await expect(auto.getByRole('region',{name:'补充待确认信息',exact:true})).toBeVisible()
 await expect(page.locator('main.main .plan-card').getByRole('button',{name:'照这个做',exact:true})).toBeDisabled()
 expect(existsSync(join(workspace,'mean.csv'))).toBe(false)
 await dawn.app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0]!.setContentSize(900,640))
 await auto.getByRole('region',{name:'补充待确认信息',exact:true}).screenshot({path:join(out,'stage-b-awaiting-info.png')})
 page=await dawn.重开();await page.getByRole('button',{name:/^请为以下具体任务自动安排/}).click();await 进坞(page,'团队')
 auto=page.getByRole('region',{name:'自动安排',exact:true})
 await expect(auto.getByRole('textbox',{name:'问题 1 的回答',exact:true})).toBeVisible()
 await auto.getByRole('textbox',{name:'问题 1 的回答',exact:true}).fill('mg/g')
 await 进坞(page,'文件');await 进坞(page,'团队')
 await expect(auto.getByRole('textbox',{name:'问题 1 的回答',exact:true})).toHaveValue('mg/g')
 await auto.getByRole('button',{name:'补充后重新规划',exact:true}).click()
 await expect(auto).toContainText('方案第 2 版')
 await expect(auto.getByRole('region',{name:'补充待确认信息',exact:true})).toHaveCount(0)
 expect(existsSync(join(workspace,'mean.csv'))).toBe(false)
 await auto.locator('.task-arrangement-result').screenshot({path:join(out,'stage-b-new-proposal.png')})
 await page.locator('main.main .plan-card[data-status="proposed"]').getByRole('button',{name:'照这个做',exact:true}).click()
 const overview=page.getByRole('region',{name:'运行总览',exact:true})
 await expect(overview.getByRole('region',{name:'批准方案执行进度',exact:true}).getByText('宿主验收通过',{exact:true})).toHaveCount(1)
 const outcome=overview.getByRole('region',{name:'协作成果',exact:true})
 await expect(outcome).toHaveAttribute('data-outcome','accepted')
 await expect(outcome.getByRole('button',{name:'查看验收成果',exact:true})).toBeVisible()
 await outcome.screenshot({path:join(out,'stage-c-summary.png')})
 await outcome.getByText('成果版本与执行额度',{exact:true}).click()
 await expect(outcome.getByRole('button',{name:/^mean.csv/})).toBeVisible()
 await outcome.screenshot({path:join(out,'stage-c-versions.png')})
 await overview.getByRole('button',{name:'展开流程工作台',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'流程工作台',exact:true})).toBeVisible()
 await page.screenshot({path:join(out,'stage-c-expanded.png')})
 await page.keyboard.press('Escape');await expect(overview.getByRole('button',{name:'展开流程工作台',exact:true})).toBeVisible()
 expect(readFileSync(join(workspace,'input.csv'),'utf8')).toBe('x\n1\n2\n3\n')
 writeFileSync(join(out,'clarification-requests.json'),JSON.stringify({requests:dawn.requests.length,realModelRequests:0,workspace,acceptedArtifactPath:'mean.csv',restarted:true,expandedReturn:true},null,2))
})

test.describe('pending clarification cancellation',()=>{
 test.use({dawnOptions:{gitInit:true,firstChunkDelayMs:2000}})
 test('stops the pending replan and retains answers without creating output',async({dawn})=>{
  const{page,workspace}=dawn;writeFileSync(join(workspace,'input.csv'),'x\n1\n2\n')
  await 在项目里开会话(page);await 进坞(page,'团队')
  const auto=page.getByRole('region',{name:'自动安排',exact:true})
  await auto.getByRole('textbox',{name:'任务目标',exact:true}).fill('计算 input.csv 均值，单位未提供')
  await auto.getByRole('button',{name:'生成安排',exact:true}).click()
  await auto.getByRole('textbox',{name:'问题 1 的回答',exact:true}).fill('mg/g')
  await auto.getByRole('button',{name:'补充后重新规划',exact:true}).click()
  await auto.getByRole('button',{name:'中止规划',exact:true}).click()
  await expect(auto.getByRole('button',{name:'补充后重新规划',exact:true})).toBeEnabled()
  await expect(auto.getByRole('textbox',{name:'问题 1 的回答',exact:true})).toHaveValue('mg/g')
  expect(existsSync(join(workspace,'mean.csv'))).toBe(false)
  await page.screenshot({path:join(out,'stage-b-cancelled.png')})
 })
})
