import { test, expect, 在项目里开会话, 进设置 } from "./fixtures.js"
import { writeFileSync } from "node:fs"
import { join } from "node:path"

for (const extension of ["R", "py"]) {
  const file = `reading.${extension}`
  const longLine = extension === "R" ? `description <- "${"长行阅读测试 / iris regression / ".repeat(12)}"` : `description = "${"长行阅读测试 / iris regression / ".repeat(12)}"`
  const code = ["# 完整脚本阅读", longLine, ...Array.from({ length: 100 }, (_, i) => extension === "R" ? `value_${i} <- ${i} # 原文与空白不应被改写` : `value_${i} = ${i} # 原文与空白不应被改写`), "", "# SCRIPT_READING_END", ""].join("\n")
  test.describe(`${extension} 长脚本`, () => {
    test.use({ dawnOptions: { toolCall: { toolName: "write", args: { path: `outputs/${file}`, content: code } } } })
    test("文件和产物可完整阅读，边框与行距独立，展开还原保留位置", async ({ dawn }, testInfo) => {
      const { page, app, workspace } = dawn
      await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setContentSize(1600, 900))
      for (let i = 0; i < 30; i++) writeFileSync(join(workspace, `navigation-${i}.txt`), "navigation fixture")
      await 在项目里开会话(page)
      const input = page.getByPlaceholder(/今天帮你做些什么/)
      await input.fill("生成长脚本"); await input.press("Enter")
      const group = page.getByRole("group", { name: "本轮生成的文件" }).last()
      await expect(group).toContainText("已生成 1 个文件")
      await group.getByRole("button", { name: "查看产物", exact: true }).click()
      const dock = page.locator(".right-dock")
      const pre = dock.locator(".preview-code")
      await expect(pre).toHaveAttribute("data-highlighted", "true")
      expect(await pre.textContent()).toBe(code)
      const frame = dock.locator(".preview-script")
      const frameStyle = await frame.evaluate(el => {
        const s = getComputedStyle(el)
        return { border: s.borderTopWidth, color: s.borderTopColor, radius: parseFloat(s.borderTopLeftRadius), padding: parseFloat(s.paddingTop) }
      })
      expect(frameStyle.border).toBe("1px")
      expect(await dock.locator(".dock-tab-btn.current").evaluate(el => getComputedStyle(el).boxShadow)).toContain(frameStyle.color)
      expect(frameStyle.radius).toBeGreaterThan(0)
      expect(frameStyle.padding).toBeGreaterThan(0)
      expect(await frame.evaluate(el => getComputedStyle(el).backgroundColor)).toBe(await dock.evaluate(el => getComputedStyle(el).backgroundColor))
      const style = await pre.evaluate(el => {
        const s = getComputedStyle(el)
        return { leading: parseFloat(s.lineHeight) / parseFloat(s.fontSize), border: s.borderTopWidth, borderStyle: s.borderTopStyle, borderColor: s.borderTopColor, stroke: s.getPropertyValue("--mix-stroke-1").trim(), radius: parseFloat(s.borderTopLeftRadius), padding: parseFloat(s.paddingTop), overflow: s.overflowY }
      })
      expect(style.leading).toBeLessThanOrEqual(1.65)
      expect(style.border).toBe("0px")
      expect(style.padding).toBe(0)
      expect(style.overflow).toBe("auto")
      await expect(dock.getByRole("button", { name: "自动换行", exact: true })).toHaveCount(0)
      await expect(dock.getByRole("button", { name: "移到废纸篓", exact: true })).toHaveCount(0)
      expect(await pre.evaluate(el => getComputedStyle(el).whiteSpace)).toBe("pre-wrap")
      expect(await pre.textContent()).toBe(code)
      const list = dock.locator(".artifacts-compact")
      await expect(list).toBeVisible()
      const artifactHeight = (await pre.boundingBox())!.height
      await pre.evaluate(el => { el.scrollTop = 120 })
      await dock.getByRole("button", { name: "展开阅读", exact: true }).click()
      await expect(list).toBeHidden()
      expect((await pre.boundingBox())!.height).toBeGreaterThan(artifactHeight + 30)
      await dock.getByRole("button", { name: "还原", exact: true }).click()
      await expect(list).toBeVisible()
      expect(await pre.evaluate(el => el.scrollTop)).toBe(120)
      await dock.getByRole("button", { name: "在文件里定位", exact: true }).click()
      await expect(page.getByRole("tab", { name: "文件", exact: true })).toHaveAttribute("aria-selected", "true")
      await expect(pre).toHaveAttribute("data-highlighted", "true")
      expect(await pre.textContent()).toBe(code)
      await page.locator(".body").evaluate(el => el.style.setProperty("--dawn-dock-w", "280px"))
      await expect.poll(() => dock.evaluate(el => el.getBoundingClientRect().width)).toBe(280)
      const tree = dock.locator(".file-tree-box")
      const navigation = tree.locator(".file-tree")
      // 定位预览不自动展开父目录；先按原入口展开，才能核对选中行。
      await navigation.getByRole("button", { name: "outputs", exact: true }).click()
      const selectedName = navigation.locator(".tree-row.active .name")
      await expect(selectedName).toHaveText(file)
      expect(await selectedName.evaluate(el => getComputedStyle(el).color)).toBe(await frame.evaluate(el => getComputedStyle(el).borderTopColor))
      expect(await selectedName.evaluate(el => Number(getComputedStyle(el).fontWeight))).toBeGreaterThan(await navigation.locator(".tree-row:not(.active) .name").first().evaluate(el => Number(getComputedStyle(el).fontWeight)))
      expect(await navigation.locator(".tree-row:not(.active) .name").first().evaluate(el => getComputedStyle(el).color)).not.toBe(await selectedName.evaluate(el => getComputedStyle(el).color))
      const fileRow = navigation.getByRole("button", { name: new RegExp(`^${file.replace(".", "\\.")}\\s`) })
      await navigation.getByRole("button", { name: /^navigation-0\.txt\s/ }).click()
      await expect(selectedName).toHaveText("navigation-0.txt")
      expect(await selectedName.evaluate(el => getComputedStyle(el).color)).toBe(await frame.evaluate(el => getComputedStyle(el).borderTopColor))
      expect(await fileRow.locator(".name").evaluate(el => getComputedStyle(el).color)).not.toBe(await selectedName.evaluate(el => getComputedStyle(el).color))
      await fileRow.click()
      await expect(selectedName).toHaveText(file)
      await expect(pre).toHaveAttribute("data-highlighted", "true")
      await expect(navigation.locator(".tree-row.active .file-when")).toHaveText(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}$/)
      await expect(navigation.locator(".tree-row.active .sub")).toContainText(/ · \d+(?:\.\d+)? (?:字节|KB|MB)/)
      expect(await tree.evaluate(el => getComputedStyle(el).borderBottomWidth)).toBe("0px")
      expect(await navigation.evaluate(el => getComputedStyle(el).paddingTop)).toBe("8px")
      const navigationStyle = await navigation.evaluate(el => {
        const s = getComputedStyle(el)
        return { borders: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth], color: s.borderTopColor, radius: parseFloat(s.borderTopLeftRadius) }
      })
      expect(navigationStyle.borders).toEqual(["1px", "1px", "1px", "1px"])
      expect(navigationStyle.color).toBe(await frame.evaluate(el => getComputedStyle(el).borderTopColor))
      expect(navigationStyle.radius).toBe(frameStyle.radius)
      expect((await navigation.boundingBox())!.x).toBeCloseTo((await frame.boundingBox())!.x, 0)
      expect((await navigation.boundingBox())!.width).toBeCloseTo((await frame.boundingBox())!.width, 0)
      const treeHandle = await tree.elementHandle()
      const treeHeight = (await tree.boundingBox())!.height
      await tree.locator(".file-tree").evaluate(el => { el.scrollTop = 90 })
      const treeScroll = await tree.locator(".file-tree").evaluate(el => el.scrollTop)
      await pre.evaluate(el => { el.scrollTop = 200 })
      const normalHeight = (await pre.boundingBox())!.height
      await dock.getByRole("button", { name: "展开阅读", exact: true }).click()
      await expect(tree).toBeHidden()
      await expect(tree).toHaveCount(1)
      expect((await pre.boundingBox())!.height).toBeGreaterThan(normalHeight + 100)
      const header = dock.locator(".preview-head")
      const headerY = (await header.boundingBox())!.y
      await pre.evaluate(el => { el.scrollTop = el.scrollHeight })
      expect((await header.boundingBox())!.y).toBe(headerY)
      expect(await pre.evaluate(el => {
        const marker = el.querySelector("[data-code-token]:last-child")!
        return marker.textContent?.includes("SCRIPT_READING_END") && marker.getBoundingClientRect().bottom <= el.getBoundingClientRect().bottom + 1
      })).toBe(true)
      await page.mouse.move(0, 0)
      await page.screenshot({ path: testInfo.outputPath(`${extension}-reading-narrow-light.png`) })
      await dock.screenshot({ path: testInfo.outputPath(`${extension}-dock-narrow-light.png`) })
      await dock.getByRole("button", { name: "还原", exact: true }).click()
      await expect(tree).toBeVisible()
      expect(await tree.evaluate((el, previous) => el === previous, treeHandle)).toBe(true)
      expect((await tree.boundingBox())!.height).toBeCloseTo(treeHeight, 0)
      expect(await tree.locator(".file-tree").evaluate(el => el.scrollTop)).toBe(treeScroll)
      await treeHandle?.dispose()
      // 回到真实 prop 宽度，再用原有加宽入口跨入宽布局。
      await page.locator(".body").evaluate(el => el.style.removeProperty("--dawn-dock-w"))
      await dock.getByRole("button", { name: "加宽", exact: true }).click()
      await expect(dock.locator(".files-wide")).toBeVisible()
      expect(await navigation.evaluate(el => getComputedStyle(el).borderRightWidth)).toBe("1px")
      expect(await navigation.evaluate(el => getComputedStyle(el).borderTopColor)).toBe(await frame.evaluate(el => getComputedStyle(el).borderTopColor))
      const normalWidth = (await pre.boundingBox())!.width
      await dock.getByRole("button", { name: "展开阅读", exact: true }).click()
      expect((await pre.boundingBox())!.width).toBeGreaterThan(normalWidth + 100)
      await page.mouse.move(0, 0)
      await page.screenshot({ path: testInfo.outputPath(`${extension}-reading-wide-light.png`) })
      await dock.screenshot({ path: testInfo.outputPath(`${extension}-dock-wide-light.png`) })
      await dock.getByRole("button", { name: "还原", exact: true }).click()
      if (extension === "py") {
        await 进设置(page, "外观")
        await page.getByRole("radio", { name: "暗色", exact: true }).click()
        await page.getByRole("radio", { name: "English", exact: true }).click()
        await page.getByRole("button", { name: "Back", exact: true }).click()
        await expect(pre).toHaveAttribute("data-highlighted", "true")
        await expect(navigation).toBeVisible()
        expect(await selectedName.evaluate(el => getComputedStyle(el).color)).toBe(await frame.evaluate(el => getComputedStyle(el).borderTopColor))
        expect(await navigation.evaluate(el => getComputedStyle(el).borderTopColor)).toBe(await frame.evaluate(el => getComputedStyle(el).borderTopColor))
        await dock.screenshot({ path: testInfo.outputPath("python-file-frame-wide-dark-english.png") })
        await dock.getByRole("button", { name: "Reading view", exact: true }).click()
        await expect(dock.getByRole("button", { name: "Wrap lines", exact: true })).toHaveCount(0)
        expect(await frame.evaluate(el => getComputedStyle(el).backgroundColor)).toBe(await dock.evaluate(el => getComputedStyle(el).backgroundColor))
        expect(await frame.evaluate(el => getComputedStyle(el).borderTopWidth)).toBe("1px")
        expect(await dock.locator(".dock-tab-btn.current").evaluate(el => getComputedStyle(el).boxShadow)).toContain(await frame.evaluate(el => getComputedStyle(el).borderTopColor))
        expect(await pre.evaluate(el => getComputedStyle(el).borderTopWidth)).toBe("0px")
        expect(await pre.textContent()).toBe(code)
        await page.screenshot({ path: testInfo.outputPath("python-reading-wide-dark-english.png") })
        await dock.screenshot({ path: testInfo.outputPath("python-dock-wide-dark-english.png") })
        await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setContentSize(1280, 650))
        await expect(dock.getByRole("button", { name: "Restore", exact: true })).toBeInViewport()
      }
    })
  })
}

const deepPath = `analysis/${"environmental_data_preparation/".repeat(10)}regression_model.py`
test.describe("长路径与受限预览高度", () => {
  test.use({ dawnOptions: { toolCall: { toolName: "write", args: { path: deepPath, content: "# long path\nprint(1)\n" } } } })
  test("操作和代码均保持可达，文件名与完整可访问路径保留", async ({ dawn }, testInfo) => {
    const { page } = dawn
    await 在项目里开会话(page)
    const input = page.getByPlaceholder(/今天帮你做些什么/)
    await input.fill("生成深层目录脚本")
    await input.press("Enter")
    const group = page.getByRole("group", { name: "本轮生成的文件" }).last()
    await expect(group).toContainText("已生成 1 个文件")
    await group.getByRole("button", { name: "查看产物", exact: true }).click()
    const dock = page.locator(".right-dock")
    await dock.getByRole("button", { name: "在文件里定位", exact: true }).click()
    await page.locator(".body").evaluate(el => el.style.setProperty("--dawn-dock-w", "280px"))
    // 等原有分栏宽度过渡结束，再比较同一布局中的上下边界。
    await expect.poll(() => dock.evaluate(el => el.getBoundingClientRect().width)).toBe(280)
    const preview = dock.locator(".file-preview")
    await preview.evaluate(el => { el.style.height = "240px"; el.style.maxHeight = "240px" })
    const code = preview.locator(".preview-code")
    await expect(code).toHaveAttribute("data-highlighted", "true")
    const pathName = preview.locator(".preview-head .name")
    await expect(pathName).toHaveText("regression_model.py")
    await expect(pathName).toHaveAttribute("aria-label", deepPath)
    await expect(pathName).toHaveAttribute("tabindex", "0")
    const bounds = (await preview.boundingBox())!
    const codeBounds = (await code.boundingBox())!
    expect(codeBounds.height).toBeGreaterThanOrEqual(40)
    expect(codeBounds.y + codeBounds.height).toBeLessThanOrEqual(bounds.y + bounds.height + 1)
    await preview.getByRole("button", { name: "展开阅读", exact: true }).click()
    await expect(dock.getByRole("button", { name: "还原", exact: true })).toBeInViewport()
    await dock.getByRole("button", { name: "还原", exact: true }).click()
    expect(await code.textContent()).toBe("# long path\nprint(1)\n")
    await dock.screenshot({ path: testInfo.outputPath("long-path-short-preview.png") })
  })
})
