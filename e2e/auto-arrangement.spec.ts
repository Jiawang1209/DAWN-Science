import {mkdirSync,writeFileSync,readFileSync,readdirSync} from 'node:fs'
import {join,resolve} from 'node:path'
import {test,expect,在项目里开会话,进坞} from './fixtures.js'
const out=resolve(process.env.DAWN_AUTO_ARRANGEMENT_EVIDENCE_DIR??'docs/validation/auto-arrangement-20261108/desktop')
test.use({dawnOptions:{gitInit:true}})
for(const [goal,count]of [['只计算 input.csv 的均值',1],['分别统计 east.csv 与 west.csv',2],['清洗、建模并独立审阅 input.csv',3]] as const){
 test(`automatically proposes ${count} task blocks for ${goal}`,async({dawn})=>{
  const{page,workspace}=dawn;mkdirSync(out,{recursive:true})
  for(const name of ['input.csv','east.csv','west.csv'])writeFileSync(join(workspace,name),'x\n1\n2\n3\n')
  await 在项目里开会话(page);await page.locator('main.main .composer textarea').fill(goal);await 进坞(page,'团队')
  let auto=page.getByRole('region',{name:'自动安排',exact:true})
  await expect(auto.locator('input[type="number"]')).toHaveCount(0)
  await expect(auto.getByRole('textbox',{name:'任务目标',exact:true})).toHaveValue(goal)
  if(count===1)await page.screenshot({path:join(out,'stage-a-auto-default.png')})
  await auto.getByRole('button',{name:'生成安排',exact:true}).click()
  await expect(auto.getByRole('status',{name:'任务块数',exact:true})).toHaveText(`${count} 个任务块`)
  await expect(auto.locator('[data-arrangement-task]')).toHaveCount(count)
  await expect(auto.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('main.main .plan-card')).toContainText(`${count} 个任务块`)
  await expect(page.locator('main.main .chip-group .chip')).toHaveCount(0)
  expect(readFileSync(join(workspace,'input.csv'),'utf8')).toBe('x\n1\n2\n3\n')
  expect(readdirSync(workspace).some(name=>name==='mean.csv'||name==='model.csv'||name==='review.md')).toBe(false)
  await auto.getByRole('status',{name:'任务块数',exact:true}).scrollIntoViewIfNeeded()
  await page.screenshot({path:join(out,`stage-b-task-${count}.png`)})
  await auto.locator('.task-arrangement-result').screenshot({path:join(out,`stage-b-result-${count}.png`)})
  if(count!==3)return
  await auto.getByText('调整任务与分工',{exact:true}).click()
  await auto.getByRole('textbox',{name:'调整要求（可选）',exact:true}).fill('合并前两步，保留独立审阅')
  await auto.getByRole('button',{name:'重新安排',exact:true}).click()
  await expect(auto.getByRole('status',{name:'任务块数',exact:true})).toHaveText('2 个任务块')
  await expect(auto.locator('[data-arrangement-task="review"]')).toContainText('独立审阅员')
  await expect(auto).toContainText('方案第 2 版')
  await auto.getByRole('status',{name:'任务块数',exact:true}).scrollIntoViewIfNeeded()
  await page.screenshot({path:join(out,'stage-b-adjusted.png')})
  await auto.locator('.task-arrangement-result').screenshot({path:join(out,'stage-b-adjusted-result.png')})
  const reopened=await dawn.重开()
  await reopened.getByRole('button',{name:/^请为以下具体任务自动安排/}).click();await 进坞(reopened,'团队')
  auto=reopened.getByRole('region',{name:'自动安排',exact:true})
  await expect(auto.getByRole('status',{name:'任务块数',exact:true})).toHaveText('2 个任务块')
  await expect(auto).toContainText('方案第 2 版')
  await expect(auto.getByText('调整任务与分工',{exact:true})).toBeVisible()
  await reopened.screenshot({path:join(out,'stage-c-restored.png')})
  const card=reopened.getByRole('region',{name:'方案第 2 版',exact:true})
  await card.getByRole('button',{name:'改一改',exact:true}).click()
  const editor=card.getByRole('textbox',{name:'方案原文',exact:true})
  const editedGoal='按用户确认的数据口径完成建模'
  const original=await editor.inputValue()
  expect(original).toContain('- 目标：清洗并完成建模')
  await editor.fill(original.replace('- 目标：清洗并完成建模','- 目标：'+editedGoal))
  await expect(card.getByRole('status',{name:'任务块数',exact:true})).toHaveText('2 个任务块')
  await card.getByRole('button',{name:'照改过的做',exact:true}).click()
  await expect(card).toHaveAttribute('data-status','approved')
  await expect(auto).toContainText(editedGoal)
  const saved=readdirSync(join(workspace,'analysis/plans')).filter(n=>n.endsWith('.md'))
  expect(saved).toHaveLength(1)
  expect(readFileSync(join(workspace,'analysis/plans',saved[0]!),'utf8')).toContain('- 目标：'+editedGoal)
  await reopened.screenshot({path:join(out,'stage-f-edited-approved.png')})
  await auto.locator('.task-arrangement-result').screenshot({path:join(out,'stage-f-approved-result.png')})
 })
}
test.describe('cancel automatic planning',()=>{
 // Tool-call replies skip mock reasoning chunks; delay the first chunk so cancellation
 // exercises a genuinely pending request rather than a proposal that already finished.
 test.use({dawnOptions:{gitInit:true,firstChunkDelayMs:2000}})
 test('cancels a real pending planning turn without running an analysis task',async({dawn})=>{
  let{page}=dawn;const{workspace}=dawn;writeFileSync(join(workspace,'input.csv'),'x\n1\n2\n')
  await 在项目里开会话(page);await 进坞(page,'团队')
  let auto=page.getByRole('region',{name:'自动安排',exact:true})
  await auto.getByRole('textbox',{name:'任务目标',exact:true}).fill('只计算 input.csv 的均值')
  await auto.getByRole('button',{name:'生成安排',exact:true}).click()
  await expect(page.locator('main.main').getByRole('button',{name:'停止',exact:true})).toBeVisible()
  await auto.getByRole('button',{name:'中止规划',exact:true}).click()
  await expect(page.locator('main.main').getByRole('button',{name:'停止',exact:true})).toHaveCount(0)
  await expect(auto.getByRole('button',{name:'生成安排',exact:true})).toBeEnabled()
  await expect(auto.getByRole('button',{name:'中止规划',exact:true})).toHaveCount(0)
  await expect(page.locator('main.main .chip-group .chip')).toHaveCount(0)
  expect(readFileSync(join(workspace,'input.csv'),'utf8')).toBe('x\n1\n2\n')
  expect(readdirSync(workspace)).not.toContain('mean.csv')
  mkdirSync(out,{recursive:true})
  await page.screenshot({path:join(out,'stage-d-cancelled.png')})
  await page.evaluate(async workspace=>{
   const invoke=(window as unknown as {dawn:{invoke:(op:string,req:unknown)=>Promise<{ok:boolean;data?:unknown}>}}).dawn.invoke
   const r=await invoke('listTasks',{})
   const owned=(r.data as {workspace?:string;sessionId?:string}[]).filter(t=>t.workspace===workspace)
   if(owned.length!==1||!owned[0]?.sessionId)throw Error('Expected one isolated task owner')
   const renamed=await invoke('renameSession',{sessionId:owned[0].sessionId,title:'规划取消恢复验收'})
   if(!renamed.ok)throw Error('Could not name the isolated cancellation case')
  },workspace)
  page=await dawn.重开()
  await page.getByRole('button',{name:/^规划取消恢复验收/}).click();await 进坞(page,'团队')
  auto=page.getByRole('region',{name:'自动安排',exact:true})
  await expect(page.locator('main.main').getByRole('button',{name:'停止',exact:true})).toHaveCount(0)
  await page.screenshot({path:join(out,'stage-e-cancelled-restored.png')})
  await auto.getByRole('textbox',{name:'任务目标',exact:true}).fill('只计算 input.csv 的均值')
  await auto.getByRole('button',{name:'生成安排',exact:true}).click()
  await expect(auto.getByRole('status',{name:'任务块数',exact:true})).toHaveText('1 个任务块')
  await expect(auto.getByRole('alert')).toHaveCount(0)
 })
})
