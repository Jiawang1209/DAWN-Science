import { test, expect, 进坞, 在项目里开会话 } from "./fixtures.js"
import { mkdirSync, writeFileSync, realpathSync } from "node:fs"
import { join } from "node:path"

test("POSIX 文件名中的反斜杠不会被改成目录分隔符", async ({ dawn }) => {
  test.skip(process.platform === "win32", "Windows does not permit literal backslashes in filenames")
  const { page, app, workspace } = dawn
  const directory = join(workspace, "folder\\name")
  mkdirSync(directory)
  writeFileSync(join(directory, "run\\final.csv"), "name,value\nliteral-backslash,7\n")
  await 进坞(page, "文件")
  const files = page.locator(".files-view")
  await files.getByRole("button", { name: "在此处浏览：folder\\name", exact: true }).click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("folder\\name")
  await files.getByRole("button", { name: /^run\\final\.csv/ }).click()
  await expect(files.locator(".table-preview")).toContainText("literal-backslash")
  await files.getByRole("button", { name: "复制当前目录完整路径", exact: true }).click()
  await expect(files.getByRole("status")).toContainText("已复制绝对路径")
  expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe(realpathSync(directory))
})

test("文件导航跨项目浏览、复制路径并保留会话工作目录", async ({ dawn }, testInfo) => {
  const { page, app, workspace, dir } = dawn
  const sibling = join(dir, "sibling")
  mkdirSync(join(workspace, "results"), { recursive: true })
  mkdirSync(sibling)
  writeFileSync(join(sibling, "兄弟目录报告.md"), "# 项目外报告\n\n外部文件可直接预览。\n\n![示例](plot.svg)\n")
  writeFileSync(join(sibling, "plot.svg"), '<svg xmlns="http://www.w3.org/2000/svg" width="200" height="120"><rect width="200" height="120" fill="#208475"/></svg>')
  await 在项目里开会话(page)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]?.setSize(1600, 1000))
  await 进坞(page, "文件")
  const files = page.locator(".files-view")
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("workspace")
  await files.getByRole("button", { name: "在此处浏览：results", exact: true }).click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("results")
  await files.getByRole("button", { name: "上一级", exact: true }).click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("workspace")
  await files.getByRole("button", { name: "上一级", exact: true }).click()
  await files.getByRole("button", { name: "在此处浏览：sibling", exact: true }).click()
  await files.getByRole("button", { name: /^兄弟目录报告\.md/ }).click()
  await expect(files.locator(".file-preview h1")).toHaveText("项目外报告")
  const image = files.locator(".file-preview img")
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate(el => (el as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await files.getByRole("button", { name: "复制当前目录完整路径", exact: true }).click()
  await expect(files.getByRole("status")).toContainText("已复制绝对路径")
  const clipboard = await app.evaluate(({ clipboard }) => clipboard.readText())
  expect(clipboard.replace(/\\/g, "/")).toBe(realpathSync(sibling).replace(/\\/g, "/"))
  const guard = await page.evaluate(async () => {
    const projects = await window.dawn!.invoke("listProjects", {})
    const project = (projects.data as { projectId: string; workspace: string }[])[0]!
    const result = await window.dawn!.invoke("readFile", { projectId: project.projectId, path: "../sibling/兄弟目录报告.md" })
    return { workspace: project.workspace, rejected: !result.ok }
  })
  expect(guard.workspace).toBe(workspace)
  expect(guard.rejected).toBe(true)
  const expanded = files.getByRole("button", { name: "加宽", exact: true })
  if (await expanded.count()) await expanded.click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("sibling")
  await page.screenshot({ path: testInfo.outputPath("navigation-light.png") })
  await page.evaluate(() => { document.documentElement.classList.add("dawn-dark") })
  await page.screenshot({ path: testInfo.outputPath("navigation-dark.png") })
  const shrink = files.getByRole("button", { name: "收窄", exact: true })
  if (await shrink.count()) await shrink.click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("sibling")
  await files.getByRole("button", { name: "输入目录路径", exact: true }).click()
  const address = files.getByRole("textbox", { name: "跳到路径", exact: true })
  await address.fill(join(sibling, "missing-directory"))
  await address.press("Enter")
  await expect(files.getByRole("alert")).toContainText("missing-directory")
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("sibling")
  await expect(files.locator(".file-preview h1")).toHaveText("项目外报告")
  await files.getByRole("button", { name: "后退", exact: true }).click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).not.toHaveText("sibling")
  await files.getByRole("button", { name: "前进", exact: true }).click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("sibling")
  await 进坞(page, "产物")
  await 进坞(page, "文件")
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("sibling")
  await files.getByRole("button", { name: "回到项目", exact: true }).click()
  await expect(files.locator('.files-breadcrumbs [aria-current="location"]')).toHaveText("workspace")
})
