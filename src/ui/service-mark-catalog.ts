const normalize = (value: string) => value.toLowerCase().replace(/[^\p{L}\p{N}]/gu, '')
const aliases = new Map(groups.flatMap(([brand, names]) => names.map(name => [normalize(name), brand] as const)))
export function serviceMarkBrand(provider?: string, label?: string): string | undefined {
  return (provider ? aliases.get(normalize(provider)) : undefined) ?? (label ? aliases.get(normalize(label)) : undefined)
}
